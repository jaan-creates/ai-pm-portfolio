import fs from 'node:fs';
import path from 'node:path';
const [root,commitSha,runId,runAttempt]=process.argv.slice(2);
if (!root || !/^[0-9a-f]{40}$/.test(commitSha) || !/^[1-9]\d*$/.test(runId) || !/^[1-9]\d*$/.test(runAttempt)) {
  throw new Error('Expected workspace, commit, run ID and run attempt');
}
const marker='// Generated by Janu release acceptance';
const name='JanuReleaseBuild.js';
const target=path.join(root,name);
if (fs.existsSync(target) && !fs.readFileSync(target,'utf8').startsWith(marker)) throw new Error('Build file collision');
const identity=JSON.stringify({commitSha,runId,runAttempt});
fs.writeFileSync(target,marker+'\nfunction readJanuReleaseBuild(){return '+identity+';}\n');
